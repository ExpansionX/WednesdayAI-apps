import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

export function deriveBuildNumber(version: string): number {
  const m = /^(\d+)\.(\d+)\.(\d+)/.exec(version.trim());
  if (!m) {
    throw new Error(
      `Cannot derive build number from non-SemVer version: ${JSON.stringify(version)}`,
    );
  }
  const [, major, minor, patch] = m.map(Number);
  if (minor >= 100 || patch >= 100) {
    throw new Error(
      `Version ${version} exceeds the two-digit minor/patch range the build-number formula supports; ` +
        `revise the formula before releasing.`,
    );
  }
  return major * 10000 + minor * 100 + patch;
}

function replaceExactlyOnce(
  content: string,
  pattern: RegExp,
  replacement: string,
  label: string,
): string {
  const matches = content.match(pattern);
  if (!matches || matches.length !== 1) {
    throw new Error(
      `Version stamp for ${label} matched ${matches ? matches.length : 0} times (expected exactly 1). ` +
        `The target file format changed — fix the stamper, do not ship a stale version.`,
    );
  }
  return content.replace(pattern, replacement);
}

export function stampAndroid(content: string, version: string, buildNumber: number): string {
  let out = replaceExactlyOnce(
    content,
    /versionName = "[^"]*"/g,
    `versionName = "${version}"`,
    "android versionName",
  );
  out = replaceExactlyOnce(
    out,
    /versionCode = \d+/g,
    `versionCode = ${buildNumber}`,
    "android versionCode",
  );
  return out;
}

export function stampPlist(content: string, version: string, buildNumber: number): string {
  let out = replaceExactlyOnce(
    content,
    /(<key>CFBundleShortVersionString<\/key>\s*\n\s*<string>)[^<]*(<\/string>)/g,
    `$1${version}$2`,
    "plist CFBundleShortVersionString",
  );
  out = replaceExactlyOnce(
    out,
    /(<key>CFBundleVersion<\/key>\s*\n\s*<string>)[^<]*(<\/string>)/g,
    `$1${buildNumber}$2`,
    "plist CFBundleVersion",
  );
  return out;
}

function replaceAtLeastOnce(
  content: string,
  pattern: RegExp,
  replacement: string,
  label: string,
): string {
  const matches = content.match(pattern);
  if (!matches || matches.length === 0) {
    throw new Error(
      `Version stamp for ${label} matched 0 times (expected at least 1). ` +
        `The target file format changed — fix the stamper, do not ship a stale version.`,
    );
  }
  return content.replace(pattern, replacement);
}

// The iOS Xcode project is generated by xcodegen from apps/ios/project.yml, whose per-target
// `info.properties` blocks are the source of truth for every target's CFBundle*Version (app +
// Share/Watch extensions). The committed Info.plists are regenerated from these, so the YAML
// must be stamped or `xcodegen generate` reverts the version. Multiple targets => replace all.
export function stampProjectYml(content: string, version: string, buildNumber: number): string {
  let out = replaceAtLeastOnce(
    content,
    /(CFBundleShortVersionString: ")[^"]*(")/g,
    `$1${version}$2`,
    "project.yml CFBundleShortVersionString",
  );
  out = replaceAtLeastOnce(
    out,
    /(CFBundleVersion: ")[^"]*(")/g,
    `$1${buildNumber}$2`,
    "project.yml CFBundleVersion",
  );
  return out;
}

type Stamper = (content: string, version: string, build: number) => string;

// Every derived app version location and the stamper that owns it. `apps/ios/project.yml` is the
// xcodegen source for the iOS app AND its Share/Watch extensions; the per-extension Info.plists
// are stamped too so the committed tree stays consistent when not regenerated.
// docs/install/updating.md is NOT here (it installs `@latest`); Peekaboo/Swabble version
// independently and are intentionally excluded. The meta-test in contracts.test.ts asserts this
// set covers every version-bearing iOS file (ADR 0004). App versions equal the synced
// CORE_VERSION — the macOS app derives its expected gateway version from the bundle version —
// and core no longer stamps these files (ADR 0097).
// Exported for the exact-content meta-test in contracts.test.ts.
export const APP_STAMPERS: Record<string, Stamper> = {
  "apps/android/app/build.gradle.kts": stampAndroid,
  "apps/ios/project.yml": stampProjectYml,
  "apps/ios/Sources/Info.plist": stampPlist,
  "apps/ios/ShareExtension/Info.plist": stampPlist,
  "apps/ios/WatchApp/Info.plist": stampPlist,
  "apps/ios/WatchExtension/Info.plist": stampPlist,
  "apps/ios/Tests/Info.plist": stampPlist,
  "apps/macos/Sources/OpenClaw/Resources/Info.plist": stampPlist,
};

export const APP_VERSION_TARGETS: readonly string[] = Object.keys(APP_STAMPERS);

// Stamp every app version location to `version`. Returns the repo-relative paths that changed.
export function stampAppVersions(version: string): string[] {
  const rootDir = resolve(".");
  const build = deriveBuildNumber(version);
  const touched: string[] = [];
  for (const [relPath, stamp] of Object.entries(APP_STAMPERS)) {
    const full = join(rootDir, relPath);
    if (!existsSync(full)) {
      continue;
    }
    const before = readFileSync(full, "utf8");
    const after = stamp(before, version, build);
    if (after !== before) {
      writeFileSync(full, after);
      touched.push(relPath);
    }
  }
  return touched;
}
