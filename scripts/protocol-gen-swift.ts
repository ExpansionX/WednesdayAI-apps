import { promises as fs, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SWIFT_MODEL_OUTPUT_PATHS } from "./protocol-swift-outputs.js";
import { isDirectRun } from "./lib/direct-run.mjs";

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: string[];
  const?: unknown;
  anyOf?: JsonSchema[];
  oneOf?: JsonSchema[];
  patternProperties?: Record<string, JsonSchema>;
  "x-schema-name"?: string;
};

export type GatewayProtocolSchema = {
  definitions: Record<string, JsonSchema>;
  "x-protocol-version": number;
  "x-error-codes": string[];
  "x-protocol-min-version"?: number;
  "x-protocol-max-version"?: number;
  "x-protocol-min-node-version"?: number;
};

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const outPaths = SWIFT_MODEL_OUTPUT_PATHS.map((relPath) => path.join(repoRoot, relPath));

// Client protocol bounds (workstream protocol-v4, phase P2): clients advertise [3, 4] and
// handle both the v3 and v4 hello/chat shapes, chosen by hello-ok.protocol. These bounds are
// client capabilities — independent of the synced schema version and of the server admission
// floors, so a gateway-only rollback to v3 never strands clients built from this revision.
// A synced contract that declares explicit bounds wins over the defaults; P4 later raises the
// client minimum after one released window.
const DEFAULT_CLIENT_MAX_PROTOCOL_VERSION = 4;
const DEFAULT_CLIENT_MIN_PROTOCOL_VERSION = 3;
const DEFAULT_CLIENT_MIN_NODE_PROTOCOL_VERSION = 3;

// Protocol v3 ↔ v4 transition: the hello shape swaps `canvasHostUrl` (v3) for
// `pluginSurfaceUrls.canvas` (v4). Emit both optionals on HelloOk regardless of which era the
// synced snapshot encodes, so hand-written canvas readers compile across the whole window and
// decode either shape (the absent field is always nil). Drop this once the window closes (P4).
const HELLO_OK_COMPAT_PROPERTIES: Record<string, JsonSchema> = {
  canvasHostUrl: { type: "string" },
  pluginSurfaceUrls: {
    type: "object",
    patternProperties: { "^(.*)$": { type: "string" } },
  },
};

const reserved: Record<string, true> = {
  associatedtype: true,
  class: true,
  deinit: true,
  enum: true,
  extension: true,
  fileprivate: true,
  func: true,
  import: true,
  init: true,
  inout: true,
  internal: true,
  let: true,
  open: true,
  operator: true,
  private: true,
  precedencegroup: true,
  protocol: true,
  public: true,
  rethrows: true,
  static: true,
  struct: true,
  subscript: true,
  typealias: true,
  var: true,
};

export function renderGatewayModels(schema: GatewayProtocolSchema): string {
  const definitions = Object.entries(schema.definitions) as Array<[string, JsonSchema]>;
  const definitionNames = new Set(definitions.map(([name]) => name));

  const errorCodeCases = schema["x-error-codes"]
    .map((c) => `    case ${camelCase(c)} = "${c}"`)
    .join("\n");

  const header = `// Generated by scripts/protocol-gen-swift.ts — do not edit by hand\n// swiftlint:disable file_length\nimport Foundation\n\npublic let GATEWAY_PROTOCOL_VERSION = ${
    schema["x-protocol-max-version"] ?? DEFAULT_CLIENT_MAX_PROTOCOL_VERSION
  }\npublic let GATEWAY_MIN_PROTOCOL_VERSION = ${
    schema["x-protocol-min-version"] ?? DEFAULT_CLIENT_MIN_PROTOCOL_VERSION
  }\npublic let GATEWAY_MIN_NODE_PROTOCOL_VERSION = ${
    schema["x-protocol-min-node-version"] ?? DEFAULT_CLIENT_MIN_NODE_PROTOCOL_VERSION
  }\n\npublic enum ErrorCode: String, Codable, Sendable {\n${errorCodeCases}\n}\n`;

  const parts: string[] = [];
  parts.push(header);

  // Value structs
  for (const [name, def] of definitions) {
    if (name === "GatewayFrame") {
      continue;
    }
    if (def.type === "object") {
      // HelloOk always carries both transition fields (see HELLO_OK_COMPAT_PROPERTIES);
      // the synced snapshot's own property set wins wherever it declares them itself, and
      // compat fields append last so existing memberwise-init argument order is stable.
      const schema = name === "HelloOk" ? withHelloCompatProperties(def) : def;
      parts.push(emitStruct(name, schema));
    } else if (def.anyOf ?? def.oneOf) {
      const union = emitDiscriminatedUnion(name, def, definitionNames);
      if (union) {
        parts.push(union);
      }
    }
  }

  // Frame enum must come after payload structs
  parts.push(emitGatewayFrame());

  return parts.join("\n");
}

function withHelloCompatProperties(def: JsonSchema): JsonSchema {
  return {
    ...def,
    properties: { ...def.properties, ...HELLO_OK_COMPAT_PROPERTIES },
  };
}

function camelCase(input: string) {
  return input
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join("");
}

function safeName(name: string) {
  const cc = camelCase(name.replace(/-/g, "_"));
  if (cc in reserved) {
    return `_${cc}`;
  }
  return cc;
}

// Core annotates every nested position that reuses a named definition with `x-schema-name`
// (core@3cac031cbc), so struct naming no longer depends on TypeBox object identity, which a
// JSON snapshot cannot express. Positions without the annotation keep their structural type.
function swiftType(schema: JsonSchema, required: boolean): string {
  const t = schema.type;
  const isOptional = !required;
  let base: string;
  const named = schema["x-schema-name"];
  if (named) {
    base = named;
  } else if (t === "string") {
    base = "String";
  } else if (t === "integer") {
    base = "Int";
  } else if (t === "number") {
    base = "Double";
  } else if (t === "boolean") {
    base = "Bool";
  } else if (t === "array") {
    base = `[${swiftType(schema.items ?? { type: "Any" }, true)}]`;
  } else if (schema.enum) {
    base = "String";
  } else if (schema.patternProperties) {
    base = "[String: AnyCodable]";
  } else if (t === "object") {
    base = "[String: AnyCodable]";
  } else {
    base = "AnyCodable";
  }
  return isOptional ? `${base}?` : base;
}

function emitStruct(name: string, schema: JsonSchema): string {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines: string[] = [];
  if (Object.keys(props).length === 0) {
    return `public struct ${name}: Codable, Sendable {}\n`;
  }
  lines.push(`public struct ${name}: Codable, Sendable {`);
  const codingKeys: string[] = [];
  for (const [key, propSchema] of Object.entries(props)) {
    const propName = safeName(key);
    const propType = swiftType(propSchema, required.has(key));
    lines.push(`    public let ${propName}: ${propType}`);
    if (propName !== key) {
      codingKeys.push(`        case ${propName} = "${key}"`);
    } else {
      codingKeys.push(`        case ${propName}`);
    }
  }
  lines.push(
    "\n    public init(\n" +
      Object.entries(props)
        .map(([key, prop]) => {
          const propName = safeName(key);
          const req = required.has(key);
          // Optional parameters default to nil. Without this, adding an optional field to the
          // protocol is a SOURCE-BREAKING change for every Swift caller of the memberwise init —
          // the parameter is optional in type but still mandatory at the call site, so callers
          // must be edited even though they have nothing to pass. That is what happened when
          // #323 added inheritedCanonicalIdentity/inheritedSenderId to AgentParams.
          // `= nil` is valid for any Optional, and only widens what compiles: existing calls that
          // pass every argument keep working.
          return `        ${propName}: ${swiftType(prop, true)}${req ? "" : "? = nil"}`;
        })
        .join(",\n") +
      ")\n" +
      "    {\n" +
      Object.entries(props)
        .map(([key]) => {
          const propName = safeName(key);
          return `        self.${propName} = ${propName}`;
        })
        .join("\n") +
      "\n    }\n\n" +
      "    private enum CodingKeys: String, CodingKey {\n" +
      codingKeys.join("\n") +
      "\n    }\n}",
  );
  lines.push("");
  return lines.join("\n");
}

// A shared tag is a property whose `const` literal exists on every branch and differs between
// them — the discriminator TypeBox unions of literal-tagged objects carry (e.g. the v4
// ChatEvent union tags every arm with `state`). Unions without one stay unemitted (the v3
// Cron*Params unions), matching the pre-v4 generator behaviour.
function findSharedConstTag(branches: JsonSchema[]): string | undefined {
  const first = branches[0]?.properties ?? {};
  for (const [key] of Object.entries(first)) {
    const literals = new Set<string>();
    let complete = true;
    for (const branch of branches) {
      const value = branch.properties?.[key]?.const;
      if (typeof value !== "string" || value.length === 0) {
        complete = false;
        break;
      }
      literals.add(value);
    }
    if (complete && literals.size === branches.length) {
      return key;
    }
  }
  return undefined;
}

type UnionArm = {
  caseName: string;
  literal: string;
  typeName: string;
  emit: boolean;
  schema: JsonSchema;
};

function emitDiscriminatedUnion(
  name: string,
  schema: JsonSchema,
  definitionNames: Set<string>,
): string | undefined {
  const branches = schema.anyOf ?? schema.oneOf;
  if (!branches || branches.length < 2) {
    return undefined;
  }
  if (branches.some((branch) => branch.type !== "object" || !branch.properties)) {
    return undefined;
  }
  const tag = findSharedConstTag(branches);
  if (!tag) {
    return undefined;
  }

  const arms: UnionArm[] = branches.map((branch) => {
    const literal = branch.properties?.[tag]?.const as string;
    const caseName = safeName(literal);
    // Named nested unions keep their nominal identity; inline branches get a structural
    // `${name}${Case}` name so unknown payloads still decode into a concrete type.
    const typeName =
      branch["x-schema-name"] ?? `${name}${caseName.charAt(0).toUpperCase()}${caseName.slice(1)}`;
    return {
      caseName,
      literal,
      typeName,
      emit: !definitionNames.has(typeName),
      schema: branch,
    };
  });
  const caseNames = new Set(arms.map((arm) => arm.caseName));
  const typeNames = new Set(arms.map((arm) => arm.typeName));
  if (caseNames.size !== arms.length || typeNames.size !== arms.length) {
    return undefined;
  }

  const lines: string[] = [];
  // Inline branch structs must exist before the enum; named ones are emitted by the
  // definitions loop (the v4 schema registers ChatDeltaEvent and friends as definitions too).
  for (const arm of arms) {
    if (arm.emit) {
      lines.push(emitStruct(arm.typeName, arm.schema));
    }
  }

  const tagName = safeName(tag);
  lines.push(`public enum ${name}: Codable, Sendable {`);
  for (const arm of arms) {
    lines.push(`    case ${arm.caseName}(${arm.typeName})`);
  }
  lines.push(`    case unknown(${tagName}: String, raw: [String: AnyCodable])`);
  lines.push("");
  lines.push("    private enum CodingKeys: String, CodingKey {");
  lines.push(
    tagName === tag ? `        case ${tagName}` : `        case ${tagName} = "${tag}"`,
  );
  lines.push("    }");
  lines.push("");
  lines.push("    public init(from decoder: Decoder) throws {");
  lines.push("        let container = try decoder.container(keyedBy: CodingKeys.self)");
  lines.push(`        let ${tagName} = try container.decode(String.self, forKey: .${tagName})`);
  lines.push(`        switch ${tagName} {`);
  for (const arm of arms) {
    lines.push(
      `        case "${arm.literal}": self = try .${arm.caseName}(${arm.typeName}(from: decoder))`,
    );
  }
  lines.push("        default:");
  lines.push(
    "            let raw = try decoder.singleValueContainer().decode([String: AnyCodable].self)",
  );
  lines.push(`            self = .unknown(${tagName}: ${tagName}, raw: raw)`);
  lines.push("        }");
  lines.push("    }");
  lines.push("");
  lines.push("    public func encode(to encoder: Encoder) throws {");
  lines.push("        switch self {");
  for (const arm of arms) {
    lines.push(`        case let .${arm.caseName}(value): try value.encode(to: encoder)`);
  }
  lines.push(`        case let .unknown(_, raw):`);
  lines.push("            var container = encoder.singleValueContainer()");
  lines.push("            try container.encode(raw)");
  lines.push("        }");
  lines.push("    }");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function emitGatewayFrame(): string {
  const cases = ["req", "res", "event"];
  const associated: Record<string, string> = {
    req: "RequestFrame",
    res: "ResponseFrame",
    event: "EventFrame",
  };
  const caseLines = cases.map((c) => `    case ${safeName(c)}(${associated[c]})`);
  const initLines = `
    private enum CodingKeys: String, CodingKey {
        case type
    }

    public init(from decoder: Decoder) throws {
        let typeContainer = try decoder.container(keyedBy: CodingKeys.self)
        let type = try typeContainer.decode(String.self, forKey: .type)
        switch type {
        case "req":
            self = try .req(RequestFrame(from: decoder))
        case "res":
            self = try .res(ResponseFrame(from: decoder))
        case "event":
            self = try .event(EventFrame(from: decoder))
        default:
            let container = try decoder.singleValueContainer()
            let raw = try container.decode([String: AnyCodable].self)
            self = .unknown(type: type, raw: raw)
        }
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
        case let .req(v):
            try v.encode(to: encoder)
        case let .res(v):
            try v.encode(to: encoder)
        case let .event(v):
            try v.encode(to: encoder)
        case let .unknown(_, raw):
            var container = encoder.singleValueContainer()
            try container.encode(raw)
        }
    }
`;

  return [
    "public enum GatewayFrame: Codable, Sendable {",
    ...caseLines,
    "    case unknown(type: String, raw: [String: AnyCodable])",
    initLines.trimEnd(),
    "}",
    "",
  ].join("\n");
}

if (isDirectRun(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}

async function main() {
  // The synced contract snapshot (ADR 0101); refreshed by `npm run contracts:sync` from a
  // WednesdayAI-core release tarball. `definitions` carries the same schemas the TypeBox
  // `ProtocolSchemas` record used to provide directly from core source.
  const schemaJson = JSON.parse(
    readFileSync(path.join(repoRoot, "apps/shared/contracts/gateway-protocol.schema.json"), "utf8"),
  ) as GatewayProtocolSchema;

  const content = renderGatewayModels(schemaJson);
  for (const outPath of outPaths) {
    await fs.mkdir(path.dirname(outPath), { recursive: true });
    await fs.writeFile(outPath, content);
    console.log(`wrote ${outPath}`);
  }
}
