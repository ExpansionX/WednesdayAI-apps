import { promises as fs, readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { SWIFT_MODEL_OUTPUT_PATHS } from "./protocol-swift-outputs.js";

type JsonSchema = {
  type?: string | string[];
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  enum?: string[];
  patternProperties?: Record<string, JsonSchema>;
};

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const outPaths = SWIFT_MODEL_OUTPUT_PATHS.map((relPath) => path.join(repoRoot, relPath));

// The synced contract snapshot (ADR 0097); refreshed by `npm run contracts:sync` from a
// WednesdayAI-core release tarball. `definitions` carries the same schemas the TypeBox
// `ProtocolSchemas` record used to provide directly from core source.
const schemaJson = JSON.parse(
  readFileSync(path.join(repoRoot, "apps/shared/contracts/gateway-protocol.schema.json"), "utf8"),
) as {
  definitions: Record<string, JsonSchema>;
  "x-protocol-version": number;
  "x-error-codes": string[];
};

const protocolVersion = schemaJson["x-protocol-version"];
const errorCodeCases = schemaJson["x-error-codes"]
  .map((c) => `    case ${camelCase(c)} = "${c}"`)
  .join("\n");

const header = `// Generated by scripts/protocol-gen-swift.ts — do not edit by hand\n// swiftlint:disable file_length\nimport Foundation\n\npublic let GATEWAY_PROTOCOL_VERSION = ${protocolVersion}\n\npublic enum ErrorCode: String, Codable, Sendable {\n${errorCodeCases}\n}\n`;

const reserved: Record<string, true> = {
  associatedtype: true,
  class: true,
  deinit: true,
  enum: true,
  extension: true,
  fileprivate: true,
  func: true,
  import: true,
  init: true,
  inout: true,
  internal: true,
  let: true,
  open: true,
  operator: true,
  private: true,
  precedencegroup: true,
  protocol: true,
  public: true,
  rethrows: true,
  static: true,
  struct: true,
  subscript: true,
  typealias: true,
  var: true,
};

function camelCase(input: string) {
  return input
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .toLowerCase()
    .split(/\s+/)
    .map((p, i) => (i === 0 ? p : p[0].toUpperCase() + p.slice(1)))
    .join("");
}

function safeName(name: string) {
  const cc = camelCase(name.replace(/-/g, "_"));
  if (cc in reserved) {
    return `_${cc}`;
  }
  return cc;
}

// Core's TypeBox source reused one schema object between a top-level definition and its nested
// uses (e.g. Snapshot embeds the PresenceEntry and StateVersion objects), and the pre-port
// generator resolved struct names from that object identity. A JSON snapshot serializes those
// uses as inline duplicates, so identity is unrecoverable — and a few inline objects
// (ResponseFrame.error, EventFrame.stateversion, WizardStep.step, WizardNextResult.step) were
// NOT shared in core despite being structurally identical to a definition. This table records
// the true shares, derived from core@0.4.11's schema source; nested uses not listed here keep
// their structural type. When core protocol work adds a new nested definition share, add the
// path here — the contracts sync PR diff makes a missing entry visible as a type widening.
const NESTED_SCHEMA_NAMES: Record<string, string> = {
  "HelloOk.snapshot": "Snapshot",
  "Snapshot.presence.items": "PresenceEntry",
  "Snapshot.stateVersion": "StateVersion",
  "SecretsResolveResult.assignments.items": "SecretsResolveAssignment",
  "SessionsCompactionListResult.checkpoints.items": "SessionsCompactionCheckpoint",
  "TasksRunsQueuedPage.runs.items": "QueuedTaskWorkRow",
  "TasksRunsHistoryPage.runs.items": "RedactedTaskRunSummary",
  "TasksRunsEventsPage.events.items": "RedactedTaskRunEvent",
  "AgentsFilesListResult.files.items": "AgentsFileEntry",
  "AgentsFilesGetResult.file": "AgentsFileEntry",
  "AgentsFilesSetResult.file": "AgentsFileEntry",
  "AgentsListResult.agents.items": "AgentSummary",
  "ModelsListResult.models.items": "ModelChoice",
  "ModelsAuthProviderStatus.profiles.items": "ModelsAuthProfileStatus",
  "ModelsAuthStatusResult.providers.items": "ModelsAuthProviderStatus",
  "ToolCatalogGroup.tools.items": "ToolCatalogEntry",
  "ToolsCatalogResult.profiles.items": "ToolCatalogProfile",
  "ToolsCatalogResult.groups.items": "ToolCatalogGroup",
};

// keyed by schema object identity within the parsed snapshot
const schemaNameByObject = new Map<object, string>();

// Paths are `Definition.prop[.items]`; `properties`/`items` container hops are implicit.
function resolveSchemaPath(schemaPath: string): object {
  const [definition, ...steps] = schemaPath.split(".");
  let node: unknown = (schemaJson.definitions as Record<string, unknown>)[definition];
  for (const key of steps) {
    if (node === null || typeof node !== "object") {
      throw new Error(`NESTED_SCHEMA_NAMES path not found in schema: ${schemaPath}`);
    }
    const container = node as Record<string, unknown>;
    if (key === "items" && "items" in container) {
      node = container.items;
    } else if (container.properties && key in (container.properties as object)) {
      node = (container.properties as Record<string, unknown>)[key];
    } else {
      throw new Error(`NESTED_SCHEMA_NAMES path not found in schema: ${schemaPath}`);
    }
  }
  if (node === null || typeof node !== "object") {
    throw new Error(`NESTED_SCHEMA_NAMES path not found in schema: ${schemaPath}`);
  }
  return node;
}

function indexNestedShares(): void {
  for (const [schemaPath, name] of Object.entries(NESTED_SCHEMA_NAMES)) {
    schemaNameByObject.set(resolveSchemaPath(schemaPath), name);
  }
}

function swiftType(schema: JsonSchema, required: boolean): string {
  const t = schema.type;
  const isOptional = !required;
  let base: string;
  const named = schemaNameByObject.get(schema as object);
  if (named) {
    base = named;
  } else if (t === "string") {
    base = "String";
  } else if (t === "integer") {
    base = "Int";
  } else if (t === "number") {
    base = "Double";
  } else if (t === "boolean") {
    base = "Bool";
  } else if (t === "array") {
    base = `[${swiftType(schema.items ?? { type: "Any" }, true)}]`;
  } else if (schema.enum) {
    base = "String";
  } else if (schema.patternProperties) {
    base = "[String: AnyCodable]";
  } else if (t === "object") {
    base = "[String: AnyCodable]";
  } else {
    base = "AnyCodable";
  }
  return isOptional ? `${base}?` : base;
}

function emitStruct(name: string, schema: JsonSchema): string {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const lines: string[] = [];
  if (Object.keys(props).length === 0) {
    return `public struct ${name}: Codable, Sendable {}\n`;
  }
  lines.push(`public struct ${name}: Codable, Sendable {`);
  const codingKeys: string[] = [];
  for (const [key, propSchema] of Object.entries(props)) {
    const propName = safeName(key);
    const propType = swiftType(propSchema, required.has(key));
    lines.push(`    public let ${propName}: ${propType}`);
    if (propName !== key) {
      codingKeys.push(`        case ${propName} = "${key}"`);
    } else {
      codingKeys.push(`        case ${propName}`);
    }
  }
  lines.push(
    "\n    public init(\n" +
      Object.entries(props)
        .map(([key, prop]) => {
          const propName = safeName(key);
          const req = required.has(key);
          // Optional parameters default to nil. Without this, adding an optional field to the
          // protocol is a SOURCE-BREAKING change for every Swift caller of the memberwise init —
          // the parameter is optional in type but still mandatory at the call site, so callers
          // must be edited even though they have nothing to pass. That is what happened when
          // #323 added inheritedCanonicalIdentity/inheritedSenderId to AgentParams.
          // `= nil` is valid for any Optional, and only widens what compiles: existing calls that
          // pass every argument keep working.
          return `        ${propName}: ${swiftType(prop, true)}${req ? "" : "? = nil"}`;
        })
        .join(",\n") +
      ")\n" +
      "    {\n" +
      Object.entries(props)
        .map(([key]) => {
          const propName = safeName(key);
          return `        self.${propName} = ${propName}`;
        })
        .join("\n") +
      "\n    }\n\n" +
      "    private enum CodingKeys: String, CodingKey {\n" +
      codingKeys.join("\n") +
      "\n    }\n}",
  );
  lines.push("");
  return lines.join("\n");
}

function emitGatewayFrame(): string {
  const cases = ["req", "res", "event"];
  const associated: Record<string, string> = {
    req: "RequestFrame",
    res: "ResponseFrame",
    event: "EventFrame",
  };
  const caseLines = cases.map((c) => `    case ${safeName(c)}(${associated[c]})`);
  const initLines = `
    private enum CodingKeys: String, CodingKey {
        case type
    }

    public init(from decoder: Decoder) throws {
        let typeContainer = try decoder.container(keyedBy: CodingKeys.self)
        let type = try typeContainer.decode(String.self, forKey: .type)
        switch type {
        case "req":
            self = try .req(RequestFrame(from: decoder))
        case "res":
            self = try .res(ResponseFrame(from: decoder))
        case "event":
            self = try .event(EventFrame(from: decoder))
        default:
            let container = try decoder.singleValueContainer()
            let raw = try container.decode([String: AnyCodable].self)
            self = .unknown(type: type, raw: raw)
        }
    }

    public func encode(to encoder: Encoder) throws {
        switch self {
        case let .req(v):
            try v.encode(to: encoder)
        case let .res(v):
            try v.encode(to: encoder)
        case let .event(v):
            try v.encode(to: encoder)
        case let .unknown(_, raw):
            var container = encoder.singleValueContainer()
            try container.encode(raw)
        }
    }
`;

  return [
    "public enum GatewayFrame: Codable, Sendable {",
    ...caseLines,
    "    case unknown(type: String, raw: [String: AnyCodable])",
    initLines.trimEnd(),
    "}",
    "",
  ].join("\n");
}

async function generate() {
  const definitions = Object.entries(schemaJson.definitions) as Array<[string, JsonSchema]>;

  indexNestedShares();

  const parts: string[] = [];
  parts.push(header);

  // Value structs
  for (const [name, schema] of definitions) {
    if (name === "GatewayFrame") {
      continue;
    }
    if (schema.type === "object") {
      parts.push(emitStruct(name, schema));
    }
  }

  // Frame enum must come after payload structs
  parts.push(emitGatewayFrame());

  const content = parts.join("\n");
  for (const outPath of outPaths) {
    await fs.mkdir(path.dirname(outPath), { recursive: true });
    await fs.writeFile(outPath, content);
    console.log(`wrote ${outPath}`);
  }
}

generate().catch((err) => {
  console.error(err);
  process.exit(1);
});
